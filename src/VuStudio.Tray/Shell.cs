/// <summary>"Start with Windows": the <c>VU Studio</c> value of the HKCU (or, from the installer, HKLM) Run key.</summary>
internal static class StartupRegistration
{
    private const string RunKey = @"Software\Microsoft\Windows\CurrentVersion\Run";
    private const string ApprovedKey = @"Software\Microsoft\Windows\CurrentVersion\Explorer\StartupApproved\Run";
    private const string ValueName = "VU Studio";

    public static bool InCurrentUser => HasValue(Registry.CurrentUser) && !DisabledInTaskManager();

    public static bool InLocalMachine => HasValue(Registry.LocalMachine);

    /// <summary>Checked when either Run key has the value.</summary>
    public static bool IsEnabled => InCurrentUser || InLocalMachine;

    public static void Enable()
    {
        using (var key = Registry.CurrentUser.CreateSubKey(RunKey, writable: true))
        {
            key.SetValue(ValueName, $"\"{Environment.ProcessPath}\" {TrayOptions.BackgroundSwitch}", RegistryValueKind.String);
        }

        // Clear a "disabled" flag left by Task Manager's Startup apps page.
        using var approved = Registry.CurrentUser.OpenSubKey(ApprovedKey, writable: true);
        approved?.DeleteValue(ValueName, throwOnMissingValue: false);
    }

    public static void Disable()
    {
        using var key = Registry.CurrentUser.OpenSubKey(RunKey, writable: true);
        key?.DeleteValue(ValueName, throwOnMissingValue: false);
    }

    private static bool HasValue(RegistryKey root)
    {
        using var key = root.OpenSubKey(RunKey);
        return key?.GetValue(ValueName) is string s && s.Length > 0;
    }

    /// <summary>Task Manager stores 12 bytes per entry; an odd first byte means disabled.</summary>
    private static bool DisabledInTaskManager()
    {
        using var key = Registry.CurrentUser.OpenSubKey(ApprovedKey);
        return key?.GetValue(ValueName) is byte[] { Length: > 0 } data && (data[0] & 1) == 1;
    }
}

/// <summary>Result of an elevated <c>sc.exe start VUStudio</c>.</summary>
internal enum ServiceStartResult
{
    Started,
    AlreadyRunning,
    Cancelled,
    NotInstalled,
    Failed,
}

internal static class ServiceStarter
{
    private const int ErrorCancelled = 1223;
    private const int ErrorServiceAlreadyRunning = 1056;
    private const int ErrorServiceDoesNotExist = 1060;

    /// <summary>Runs <c>%SystemRoot%\System32\sc.exe start VUStudio</c> through UAC (ShellExecute "runas").</summary>
    public static async Task<(ServiceStartResult Result, int Code)> StartAsync(CancellationToken ct)
    {
        var info = new ProcessStartInfo(Path.Combine(Environment.SystemDirectory, "sc.exe"), $"start {ServiceLocator.ServiceName}")
        {
            UseShellExecute = true,
            Verb = "runas",
            WindowStyle = ProcessWindowStyle.Hidden,
        };

        try
        {
            using var process = Process.Start(info);
            if (process is null)
            {
                return (ServiceStartResult.Failed, -1);
            }

            await process.WaitForExitAsync(ct).ConfigureAwait(false);
            int exitCode;
            try
            {
                exitCode = process.ExitCode;
            }
            catch (Exception ex) when (ex is InvalidOperationException or Win32Exception)
            {
                return (ServiceStartResult.Started, 0); // exit code not readable: the status poll tells the truth
            }

            return exitCode switch
            {
                0 => (ServiceStartResult.Started, 0),
                ErrorServiceAlreadyRunning => (ServiceStartResult.AlreadyRunning, ErrorServiceAlreadyRunning),
                ErrorServiceDoesNotExist => (ServiceStartResult.NotInstalled, ErrorServiceDoesNotExist),
                var code => (ServiceStartResult.Failed, code),
            };
        }
        catch (Win32Exception ex) when (ex.NativeErrorCode == ErrorCancelled)
        {
            return (ServiceStartResult.Cancelled, ErrorCancelled);
        }
    }
}
