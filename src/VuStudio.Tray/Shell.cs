/// <summary>Command line: <c>--background</c> (start in the tray, used by the Run key) and <c>--port N</c>.</summary>
internal sealed record TrayOptions(bool Background, int? Port)
{
    public const string BackgroundSwitch = "--background";

    public static TrayOptions Parse(string[] args)
    {
        var background = false;
        int? port = null;
        for (var i = 0; i < args.Length; i++)
        {
            var arg = args[i];
            if (arg.Equals(BackgroundSwitch, StringComparison.OrdinalIgnoreCase) || arg.Equals("--tray", StringComparison.OrdinalIgnoreCase))
            {
                background = true;
            }
            else if (arg.StartsWith("--port", StringComparison.OrdinalIgnoreCase))
            {
                var value = arg.Contains('=') ? arg[(arg.IndexOf('=') + 1)..] : i + 1 < args.Length ? args[++i] : null;
                port = int.TryParse(value, NumberStyles.None, CultureInfo.InvariantCulture, out var p) ? p : null;
            }
        }

        return new TrayOptions(background, port);
    }
}

/// <summary>The application icon, embedded from <c>Assets/vustudio.ico</c> (generated by <c>Assets/generate-icon.py</c>).</summary>
internal static class AppIcon
{
    public static Icon Load(Size? size = null)
    {
        using var stream = typeof(AppIcon).Assembly.GetManifestResourceStream("VuStudio.Tray.vustudio.ico")
            ?? throw new InvalidOperationException("The embedded icon is missing.");
        return size is { } s ? new Icon(stream, s) : new Icon(stream);
    }
}

/// <summary>
/// One tray per user session: a named mutex <c>Local\VuStudio.Tray</c>. A second launch sets the named event
/// <c>Local\VuStudio.Tray.Show</c>, which makes the first instance open its window, and exits.
/// </summary>
internal sealed class SingleInstance : IDisposable
{
    private const string MutexName = @"Local\VuStudio.Tray";
    private const string ShowEventName = @"Local\VuStudio.Tray.Show";

    private readonly Mutex _mutex;
    private readonly EventWaitHandle _showEvent;
    private RegisteredWaitHandle? _registration;
    private int _disposed;

    private SingleInstance(Mutex mutex, EventWaitHandle showEvent)
    {
        _mutex = mutex;
        _showEvent = showEvent;
    }

    /// <summary>Returns the instance guard, or <c>null</c> when another instance already runs (and was signalled).</summary>
    public static SingleInstance? TryAcquire()
    {
        var mutex = new Mutex(initiallyOwned: true, MutexName, out var createdNew);
        if (!createdNew)
        {
            mutex.Dispose();
            SignalExisting();
            return null;
        }

        return new SingleInstance(mutex, new EventWaitHandle(false, EventResetMode.AutoReset, ShowEventName));
    }

    /// <summary>Invokes <paramref name="onShow"/> on a pool thread whenever another launch asks for the window.</summary>
    public void ListenForShow(Action onShow) =>
        _registration = ThreadPool.RegisterWaitForSingleObject(_showEvent, (_, _) => onShow(), null, Timeout.Infinite, executeOnlyOnce: false);

    public void Dispose()
    {
        if (Interlocked.Exchange(ref _disposed, 1) == 1)
        {
            return;
        }

        _registration?.Unregister(null);
        _showEvent.Dispose();
        try
        {
            _mutex.ReleaseMutex();
        }
        catch (ApplicationException)
        {
            // Not owned by this thread (disposed from another thread): closing the handle is enough.
        }

        _mutex.Dispose();
    }

    private static void SignalExisting()
    {
        // The first instance creates the event right after the mutex: retry briefly.
        for (var attempt = 0; attempt < 20; attempt++)
        {
            try
            {
                using var show = EventWaitHandle.OpenExisting(ShowEventName);
                NativeMethods.AllowSetForegroundWindow(NativeMethods.ASFW_ANY); // let it come to the front
                show.Set();
                return;
            }
            catch (WaitHandleCannotBeOpenedException)
            {
                Thread.Sleep(100);
            }
        }
    }
}

/// <summary>
/// A hidden top-level window (message-only windows do not receive broadcasts) for
/// <c>WM_DWMCOLORIZATIONCOLORCHANGED</c>, <c>WM_SETTINGCHANGE("ImmersiveColorSet")</c> and <c>WM_ENDSESSION</c>.
/// </summary>
internal sealed class BroadcastWindow : NativeWindow, IDisposable
{
    public BroadcastWindow() => CreateHandle(new CreateParams { Caption = "VU Studio broadcast listener" });

    public event EventHandler? ColorsChanged;

    public event EventHandler? SessionEnding;

    public void Dispose() => DestroyHandle();

    protected override void WndProc(ref Message m)
    {
        switch (m.Msg)
        {
            case NativeMethods.WM_DWMCOLORIZATIONCOLORCHANGED:
            case NativeMethods.WM_THEMECHANGED:
                ColorsChanged?.Invoke(this, EventArgs.Empty);
                break;
            case NativeMethods.WM_SETTINGCHANGE when m.LParam != 0 && System.Runtime.InteropServices.Marshal.PtrToStringUni(m.LParam) == "ImmersiveColorSet":
                ColorsChanged?.Invoke(this, EventArgs.Empty);
                break;
            case NativeMethods.WM_ENDSESSION when m.WParam != 0:
                SessionEnding?.Invoke(this, EventArgs.Empty);
                break;
        }

        base.WndProc(ref m);
    }
}

/// <summary>Per-user window placement, in <c>%LocalAppData%\VU Studio\tray.json</c>.</summary>
internal sealed class WindowSettings
{
    public int X { get; set; }

    public int Y { get; set; }

    public int Width { get; set; }

    public int Height { get; set; }

    public bool Maximized { get; set; }

    public static string FilePath => Path.Combine(TrayPaths.LocalData, "tray.json");

    public static WindowSettings? Load()
    {
        try
        {
            return File.Exists(FilePath) ? JsonSerializer.Deserialize<WindowSettings>(File.ReadAllText(FilePath)) : null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or JsonException)
        {
            return null;
        }
    }

    public void Save()
    {
        try
        {
            Directory.CreateDirectory(TrayPaths.LocalData);
            var temp = FilePath + ".tmp";
            File.WriteAllText(temp, JsonSerializer.Serialize(this));
            File.Move(temp, FilePath, overwrite: true);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
        }
    }
}

